"""Generate an eval set for the demo corpus: data/demo/questions.yaml.

    python demo/make_demo_questions.py
    python evals/run_eval.py --questions data/demo/questions.yaml --split all

Deterministic (fixed seed) for a given corpus. Lookups quote the opening of a
paper's abstract, so they test the pipeline end to end rather than hard
paraphrase retrieval. Counts are computed from the corpus at scoring time.
"Not in the library" topics are checked absent from every demo card here.
"""
from __future__ import annotations

import random
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEMO = ROOT / "data" / "demo"
ABSENT = {
    "protein structure prediction": r"protein fold|alphafold|protein structure",
    "exoplanet atmospheres": r"exoplanet",
    "sourdough fermentation": r"sourdough|fermentation",
    "quantum error correction": r"quantum error|surface code",
}


def cards() -> list[dict]:
    out = []
    for p in sorted((DEMO / "papers").glob("*.md")):
        t = p.read_text(encoding="utf-8")
        field = lambda k: (re.search(rf'^{k}:\s*"?(.*?)"?\s*$', t, re.M) or [None, ""])[1]  # noqa: E731
        m = re.search(r"^> (.+)$", t, re.M)
        out.append({"file": p.name, "group": field("research"), "year": field("year"),
                    "subtheme": field("subtheme"), "abstract": m.group(1) if m else "", "text": t.lower()})
    return out


def opening(abstract: str, words: int = 22) -> str:
    return " ".join(abstract.split()[:words]).rstrip(",;:") + " …"


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    cs = cards()
    if not cs:
        print("no demo cards: run demo/build_demo_corpus.py first")
        return 1
    rng = random.Random(20261029)
    by_group = {g: [c for c in cs if c["group"] == g] for g in sorted({c["group"] for c in cs})}
    groups = list(by_group)
    items = []

    def add(kind, q, split, **extra):
        items.append({"id": f"D{len(items) + 1:02d}", "kind": kind, "split": split, "q": q, **extra})

    for i, c in enumerate(rng.sample(cs, 8)):
        add("lookup", f'Which paper in my library begins: "{opening(c["abstract"])}"?',
            "dev" if i % 2 else "test", expect=[c["file"]])
    years = sorted({c["year"] for c in cs if c["year"]})
    for i, y in enumerate(rng.sample(years, 2)):
        add("count", f"How many papers in my library were published in {y}?", ["dev", "test"][i],
            where={"year": y})
    top_sub = max({c["subtheme"] for c in cs}, key=lambda s: sum(c["subtheme"] == s for c in cs))
    add("count", f"How many papers in my library have the subtheme {top_sub}?", "dev", where={"subtheme": top_sub})
    for i, (topic, pattern) in enumerate(ABSENT.items()):
        if not any(re.search(pattern, c["text"]) for c in cs):
            add("unanswerable", f"Which papers in my library are about {topic}?", ["dev", "test"][i % 2])
    # Access: users scoped to one group (settings.yaml demo roles).
    users = {"pedestrian-safety": "safety-analyst", "ev-charging": "energy-analyst"}
    for i, g in enumerate(groups):
        other = groups[1 - i]
        c = rng.choice(by_group[other])
        add("forbidden", f'Which paper in my library begins: "{opening(c["abstract"])}"?', "test",
            user=users[g], **{"from": c["file"]})
        c = rng.choice(by_group[g])
        add("lookup", f'Which paper in my library begins: "{opening(c["abstract"])}"?', "dev",
            user=users[g], expect=[c["file"]])
    add("count", "How many papers in my library were published after 2020?", "test",
        user="visitor", where={"year_in": [y for y in years if y.isdigit() and int(y) > 2020]})
    spec = {"version": 1, "note": "generated by demo/make_demo_questions.py", "items": items}
    out = DEMO / "questions.yaml"
    out.write_text(yaml.safe_dump(spec, allow_unicode=True, sort_keys=False, width=1000), encoding="utf-8")
    kinds = {k: sum(i["kind"] == k for i in items) for k in ("lookup", "count", "unanswerable", "forbidden")}
    print(f"{len(items)} questions -> {out}  {kinds}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
